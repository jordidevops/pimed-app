CREATE OR REPLACE FUNCTION api.create_employee_portal_token(
  p_employee_id   uuid,
  p_token_hash    bytea,
  p_label         text DEFAULT NULL,
  p_pin_hash      text DEFAULT NULL,
  p_expires_at    timestamptz DEFAULT NULL,
  p_shared_device boolean DEFAULT false
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = data, api, public
AS $$
DECLARE
  v_emp record;
  v_token_id uuid;
BEGIN
  IF p_token_hash IS NULL OR length(p_token_hash) = 0 THEN
    RAISE EXCEPTION 'invalid_token_hash' USING ERRCODE = 'check_violation';
  END IF;

  SELECT e.id, e.tenant_id, e.site_id, e.status
  INTO v_emp
  FROM data.employees e
  WHERE e.id = p_employee_id;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'employee_not_found: %', p_employee_id USING ERRCODE = 'no_data_found';
  END IF;

  IF v_emp.status IS DISTINCT FROM 'active' THEN
    RAISE EXCEPTION 'employee_not_active' USING ERRCODE = 'check_violation';
  END IF;

  IF NOT data.jwt_has_permission(v_emp.tenant_id, 'attendance.manage', v_emp.site_id) THEN
    RAISE EXCEPTION 'insufficient_privilege: attendance.manage required'
      USING ERRCODE = 'insufficient_privilege';
  END IF;

  INSERT INTO data.employee_portal_tokens (
    tenant_id,
    employee_id,
    token_hash,
    pin_hash,
    expires_at,
    label,
    shared_device,
    created_by_user_id
  ) VALUES (
    v_emp.tenant_id,
    v_emp.id,
    p_token_hash,
    p_pin_hash,
    p_expires_at,
    NULLIF(btrim(p_label), ''),
    COALESCE(p_shared_device, false),
    auth.uid()
  )
  RETURNING id INTO v_token_id;

  RETURN jsonb_build_object('token_id', v_token_id);
EXCEPTION
  WHEN unique_violation THEN
    RAISE EXCEPTION 'duplicate_active_label'
      USING ERRCODE = 'unique_violation',
            DETAIL = 'Ja existeix un token permanent actiu amb aquesta etiqueta per l''empleat.';
END;
$$;

CREATE OR REPLACE FUNCTION api.revoke_employee_portal_token(
  p_token_id     uuid,
  p_reason       text DEFAULT NULL,
  p_compromised  boolean DEFAULT false
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = data, api, public
AS $$
DECLARE
  v_token record;
BEGIN
  SELECT t.id, t.tenant_id, t.employee_id, t.is_active, t.revoked_at, t.session_version
  INTO v_token
  FROM data.employee_portal_tokens t
  WHERE t.id = p_token_id;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'token_not_found: %', p_token_id USING ERRCODE = 'no_data_found';
  END IF;

  IF NOT data.jwt_has_permission(v_token.tenant_id, 'attendance.manage') THEN
    RAISE EXCEPTION 'insufficient_privilege: attendance.manage required'
      USING ERRCODE = 'insufficient_privilege';
  END IF;

  IF v_token.revoked_at IS NOT NULL OR NOT v_token.is_active THEN
    RETURN jsonb_build_object(
      'token_id', v_token.id,
      'already_revoked', true,
      'session_version', v_token.session_version
    );
  END IF;

  UPDATE data.employee_portal_tokens
  SET
    is_active = false,
    revoked_at = now(),
    revoke_reason = NULLIF(btrim(p_reason), ''),
    compromised = COALESCE(p_compromised, false),
    session_version = session_version + 1
  WHERE id = p_token_id
  RETURNING session_version INTO v_token.session_version;

  RETURN jsonb_build_object(
    'token_id', p_token_id,
    'revoked', true,
    'session_version', v_token.session_version,
    'compromised', COALESCE(p_compromised, false)
  );
END;
$$;

CREATE OR REPLACE FUNCTION api.list_employee_portal_tokens(p_employee_id uuid)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = data, api, public
AS $$
DECLARE
  v_emp record;
  v_rows jsonb;
BEGIN
  SELECT e.id, e.tenant_id, e.site_id
  INTO v_emp
  FROM data.employees e
  WHERE e.id = p_employee_id;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'employee_not_found: %', p_employee_id USING ERRCODE = 'no_data_found';
  END IF;

  IF NOT data.jwt_has_permission(v_emp.tenant_id, 'attendance.manage', v_emp.site_id) THEN
    RAISE EXCEPTION 'insufficient_privilege: attendance.manage required'
      USING ERRCODE = 'insufficient_privilege';
  END IF;

  SELECT COALESCE(jsonb_agg(row_to_json(t)::jsonb ORDER BY t.created_at DESC), '[]'::jsonb)
  INTO v_rows
  FROM api.employee_portal_tokens t
  WHERE t.employee_id = p_employee_id;

  RETURN v_rows;
END;
$$;

CREATE OR REPLACE FUNCTION api.list_employee_portal_access_logs(
  p_token_id uuid,
  p_limit    integer DEFAULT 50
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = data, api, public
AS $$
DECLARE
  v_token record;
  v_rows jsonb;
  v_limit integer := LEAST(GREATEST(COALESCE(p_limit, 50), 1), 200);
BEGIN
  SELECT t.id, t.tenant_id, t.employee_id
  INTO v_token
  FROM data.employee_portal_tokens t
  WHERE t.id = p_token_id;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'token_not_found: %', p_token_id USING ERRCODE = 'no_data_found';
  END IF;

  IF NOT data.jwt_has_permission(v_token.tenant_id, 'attendance.manage') THEN
    RAISE EXCEPTION 'insufficient_privilege: attendance.manage required'
      USING ERRCODE = 'insufficient_privilege';
  END IF;

  SELECT COALESCE(jsonb_agg(row_to_json(l)::jsonb ORDER BY l.accessed_at DESC), '[]'::jsonb)
  INTO v_rows
  FROM (
    SELECT
      l.id,
      l.token_id,
      l.employee_id,
      l.tenant_id,
      l.accessed_at,
      l.ip_address::text AS ip_address,
      l.user_agent,
      l.action,
      l.http_status,
      l.failure_reason
    FROM data.employee_portal_access_logs l
    WHERE l.token_id = p_token_id
    ORDER BY l.accessed_at DESC
    LIMIT v_limit
  ) l;

  RETURN v_rows;
END;
$$;

