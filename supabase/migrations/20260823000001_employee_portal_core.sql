CREATE OR REPLACE FUNCTION data.create_employee_portal_access_logs_partition(p_month_start date)
RETURNS void
LANGUAGE plpgsql
AS $$
DECLARE
  v_month_end date := (p_month_start + interval '1 month')::date;
  v_table_name text := 'employee_portal_access_logs_'
    || to_char(p_month_start, 'YYYY_MM');
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_class c
    JOIN pg_namespace n ON n.oid = c.relnamespace
    WHERE n.nspname = 'data' AND c.relname = v_table_name
  ) THEN
    EXECUTE format(
      'CREATE TABLE data.%I PARTITION OF data.employee_portal_access_logs FOR VALUES FROM (%L) TO (%L)',
      v_table_name,
      p_month_start,
      v_month_end
    );
  END IF;
END;
$$;

