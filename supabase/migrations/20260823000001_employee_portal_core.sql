-- -----------------------------------------------------------------------------
-- 1. data.employee_portal_tokens
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS data.employee_portal_tokens (
  id                  uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  tenant_id           uuid NOT NULL REFERENCES data.tenants(id) ON DELETE CASCADE,
  employee_id         uuid NOT NULL REFERENCES data.employees(id) ON DELETE CASCADE,

  token_hash          bytea NOT NULL,
  pin_hash            text,
  pin_attempts        smallint NOT NULL DEFAULT 0,
  pin_locked_until    timestamptz,
  session_version     integer NOT NULL DEFAULT 1,
  compromised         boolean NOT NULL DEFAULT false,

  expires_at          timestamptz,
  is_active           boolean NOT NULL DEFAULT true,

  label               text,
  shared_device       boolean NOT NULL DEFAULT false,
  last_accessed_at    timestamptz,

  created_by_user_id  uuid REFERENCES data.profiles(id) ON DELETE SET NULL,
  created_at          timestamptz NOT NULL DEFAULT now(),
  revoked_at          timestamptz,
  revoke_reason       text,

  CONSTRAINT employee_portal_tokens_pin_attempts_nonneg
    CHECK (pin_attempts >= 0),
  CONSTRAINT employee_portal_tokens_session_version_positive
    CHECK (session_version > 0)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_employee_portal_tokens_hash
  ON data.employee_portal_tokens (token_hash);

CREATE UNIQUE INDEX IF NOT EXISTS uq_employee_portal_tokens_active_label
  ON data.employee_portal_tokens (employee_id, label)
  WHERE is_active = true
    AND revoked_at IS NULL
    AND expires_at IS NULL
    AND label IS NOT NULL;

CREATE INDEX IF NOT EXISTS idx_employee_portal_tokens_employee_active
  ON data.employee_portal_tokens (employee_id, is_active)
  WHERE revoked_at IS NULL;

CREATE INDEX IF NOT EXISTS idx_employee_portal_tokens_tenant
  ON data.employee_portal_tokens (tenant_id, created_at DESC);

COMMENT ON TABLE data.employee_portal_tokens IS
  'Tokens d''accés al portal empleat. Només token_hash (SHA-256); el secret mai es persisteix.';
COMMENT ON COLUMN data.employee_portal_tokens.token_hash IS
  'SHA-256 del secret d''URL (/e/{secret}). Generat a capa app abans de la RPC.';
COMMENT ON COLUMN data.employee_portal_tokens.compromised IS
  'Revocació d''emergència: invalida qualsevol JWT existent al següent refresh.';

