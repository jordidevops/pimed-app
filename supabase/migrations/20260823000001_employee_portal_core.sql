CREATE OR REPLACE FUNCTION data.trg_audit_employee_portal_tokens()
RETURNS TRIGGER
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = data
AS $$
DECLARE
  v_site_id uuid;
BEGIN
  SELECT e.site_id INTO v_site_id
  FROM data.employees e
  WHERE e.id = COALESCE(NEW.employee_id, OLD.employee_id);

  IF TG_OP = 'INSERT' THEN
    PERFORM data.log_audit_event(
      NEW.tenant_id,
      COALESCE(auth.uid(), NEW.created_by_user_id),
      v_site_id,
      'EMPLOYEE_PORTAL_TOKEN_CREATED',
      'employee_portal_token',
      NEW.id,
      jsonb_build_object(
        'employee_id', NEW.employee_id,
        'label', NEW.label,
        'shared_device', NEW.shared_device,
        'expires_at', NEW.expires_at,
        'pin_required', (NEW.pin_hash IS NOT NULL)
      )
    );
    RETURN NEW;
  END IF;

  IF TG_OP = 'UPDATE'
     AND OLD.revoked_at IS NULL
     AND NEW.revoked_at IS NOT NULL THEN
    PERFORM data.log_audit_event(
      NEW.tenant_id,
      auth.uid(),
      v_site_id,
      'EMPLOYEE_PORTAL_TOKEN_REVOKED',
      'employee_portal_token',
      NEW.id,
      jsonb_build_object(
        'employee_id', NEW.employee_id,
        'label', NEW.label,
        'revoke_reason', NEW.revoke_reason,
        'compromised', NEW.compromised,
        'session_version', NEW.session_version
      )
    );
  END IF;

  RETURN NEW;
END;
$$;

DROP TRIGGER IF EXISTS trg_audit_employee_portal_tokens ON data.employee_portal_tokens;
CREATE TRIGGER trg_audit_employee_portal_tokens
  AFTER INSERT OR UPDATE ON data.employee_portal_tokens
  FOR EACH ROW EXECUTE FUNCTION data.trg_audit_employee_portal_tokens();

