CREATE TABLE IF NOT EXISTS data.employee_portal_access_logs (
  id              bigint GENERATED BY DEFAULT AS IDENTITY,
  token_id        uuid NOT NULL REFERENCES data.employee_portal_tokens(id) ON DELETE CASCADE,
  employee_id     uuid NOT NULL REFERENCES data.employees(id) ON DELETE CASCADE,
  tenant_id       uuid NOT NULL REFERENCES data.tenants(id) ON DELETE CASCADE,

  accessed_at     timestamptz NOT NULL DEFAULT now(),
  ip_address      inet,
  user_agent      text,

  action          text NOT NULL,
  http_status     smallint,
  failure_reason  text,

  PRIMARY KEY (id, accessed_at),
  CONSTRAINT employee_portal_access_logs_action_check CHECK (action IN (
    'view_schedule',
    'view_history',
    'punch_in',
    'punch_out',
    'pin_failed',
    'token_invalid',
    'token_expired',
    'session_create',
    'session_refresh'
  ))
) PARTITION BY RANGE (accessed_at);

