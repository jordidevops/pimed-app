CREATE OR REPLACE FUNCTION data.deactivate_expired_employee_portal_tokens()
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = data, public
AS $$
DECLARE
  v_count integer;
BEGIN
  UPDATE data.employee_portal_tokens
  SET
    is_active = false,
    session_version = session_version + 1
  WHERE is_active = true
    AND expires_at IS NOT NULL
    AND expires_at < now()
    AND revoked_at IS NULL;

  GET DIAGNOSTICS v_count = ROW_COUNT;
  RETURN v_count;
END;
$$;

CREATE OR REPLACE FUNCTION data.cleanup_employee_portal_access_logs(p_retention_days integer DEFAULT 90)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = data, public
AS $$
DECLARE
  v_count integer;
BEGIN
  DELETE FROM data.employee_portal_access_logs
  WHERE accessed_at < now() - make_interval(days => GREATEST(p_retention_days, 1));

  GET DIAGNOSTICS v_count = ROW_COUNT;
  RETURN v_count;
END;
$$;

DO $$
DECLARE
  v_job_id bigint;
BEGIN
  IF EXISTS (SELECT 1 FROM pg_extension WHERE extname = 'pg_cron') THEN
    SELECT jobid INTO v_job_id
    FROM cron.job
    WHERE jobname = 'deactivate-expired-employee-portal-tokens'
    LIMIT 1;
    IF v_job_id IS NOT NULL THEN
      PERFORM cron.unschedule(v_job_id);
    END IF;
    PERFORM cron.schedule(
      'deactivate-expired-employee-portal-tokens',
      '15 3 * * *',
      'SELECT data.deactivate_expired_employee_portal_tokens();'
    );

    SELECT jobid INTO v_job_id
    FROM cron.job
    WHERE jobname = 'cleanup-employee-portal-access-logs'
    LIMIT 1;
    IF v_job_id IS NOT NULL THEN
      PERFORM cron.unschedule(v_job_id);
    END IF;
    PERFORM cron.schedule(
      'cleanup-employee-portal-access-logs',
      '30 4 * * 0',
      'SELECT data.cleanup_employee_portal_access_logs(90);'
    );
  END IF;
END;
$$;

